def frontmatter(
    kind: str,
    title: str,
    identifier: str,
    release_version: str,
    *,
    controlled_tags: Sequence[str] = (),
) -> str:
    lines = [
        "---",
        f"id: {yaml_value(identifier)}",
        f"kind: {yaml_value(kind)}",
        f"title: {yaml_value(title)}",
    ]
    if controlled_tags:
        # `тип/тема` is kept as a controlled Russian scalar so the actual
        # Obsidian tag list stays within the requested 5–7 tags per page.
        lines.extend(
            (
                f"версия_схемы: {yaml_value(TOPIC_SCHEMA_VERSION)}",
                f"тип: {yaml_value('тип/тема')}",
                "tags:",
            )
        )
        lines.extend(f"  - {yaml_value(tag)}" for tag in controlled_tags)
    lines.extend(
        (
            "generated: true",
            f"generator: {yaml_value(GENERATOR_ID)}",
            f"instruction_state: {yaml_value(INSTRUCTION_STATE)}",
            f"catalog_release: {yaml_value(release_version)}",
            "---",
        )
    )
    return "\n".join(lines)


