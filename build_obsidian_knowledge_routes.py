RAW_BACKEND_RE = re.compile(
    r"\b(?:TD-[A-Z0-9-]+|GAP-\d+|P[0-4]_(?:RED|ORANGE|YELLOW|GREEN|BLUE)|SL[0-6]|S[0-4]_[A-Z0-9_]+|ALLOW|DENY|MISSING|UNASSIGNED|TBD_NOT_SCHEDULED)\b"
)
WIKILINK_RE = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]+)?(?:\|[^\]]+)?\]\]")


def generated_target(filename: str) -> str:
    return f"{OUT.name}/{Path(filename).with_suffix('').as_posix()}"


def resolve_wikilink(target: str, desired_names: Set[str]) -> bool:
    target = target.strip()
    if not target:
        return False
    desired_targets = {generated_target(name) for name in desired_names}
    if target.removesuffix(".md") in desired_targets:
        return True
    direct = VAULT / target
    candidates = [direct, Path(str(direct) + ".md")]
    if any(path.is_file() for path in candidates):
        return True
    return False


def section_link_count(content: str, heading: str) -> int:
    start_token = f"## {heading}\n"
    start = content.find(start_token)
    if start < 0:
        return 0
    start += len(start_token)
    next_heading = content.find("\n## ", start)
    details = content.find("\n<details>", start)
    boundaries = [value for value in (next_heading, details) if value >= 0]
    end = min(boundaries) if boundaries else len(content)
    section = content[start:end]
    return len(WIKILINK_RE.findall(section))


def section_text(content: str, heading: str) -> str:
    start_token = f"## {heading}\n"
    start = content.find(start_token)
    if start < 0:
        return ""
    start += len(start_token)
    next_heading = content.find("\n## ", start)
    details = content.find("\n<details>", start)
    boundaries = [value for value in (next_heading, details) if value >= 0]
    end = min(boundaries) if boundaries else len(content)
    return content[start:end]


def verify_rendered(rendered: Mapping[str, str]) -> Dict[str, int]:
    desired_names = set(rendered)
    errors: List[str] = []
    wiki_count = 0
    raw_first_screen = 0
    navigation_home_links = 0
    topic_navigation_links = 0
    semantic_topic_links = 0
    all_future_card_names = [name for names in FUTURE_CARD_NAMES.values() for name in names]
    future_cards = len(all_future_card_names)
    unique_future_cards = len(set(all_future_card_names))
    index = rendered[INDEX_NAME]

    expected_pages = 1 + len(ROUTES) + len(TOPICS)
    if len(rendered) != expected_pages:
        errors.append(f"expected {expected_pages} pages, got {len(rendered)}")
    if set(TOPICS) != set(SEMANTIC_RELATIONS):
        errors.append("semantic relation map does not cover exactly all topics")
    if set(TOPICS) != set(FUTURE_CARD_NAMES) or set(TOPICS) != set(CARD_CONTEXTS):
        errors.append("future-card registry does not cover exactly all topics")
    if future_cards < 400:
        errors.append(f"future-card registry is too small: {future_cards}, expected at least 400")
    if unique_future_cards != future_cards:
        errors.append(f"future-card titles must be globally unique: {unique_future_cards} of {future_cards}")

    declared_edges = [
        (source, relation_type, target)
        for source, relations in SEMANTIC_RELATIONS.items()
        for relation_type, target in relations
    ]
    directed_pairs = {(source, target) for source, _, target in declared_edges}
    reciprocal_pairs = {
        tuple(sorted((source, target)))
        for source, target in directed_pairs
        if (target, source) in directed_pairs
    }
    if len(directed_pairs) != len(declared_edges):
        errors.append("semantic graph repeats a directed source-target pair")
    if reciprocal_pairs:
        errors.append(f"semantic graph has reciprocal pairs: {sorted(reciprocal_pairs)}")

    prerequisite_edges = [(source, target) for source, relation_type, target in declared_edges if relation_type == "нужно до"]
    prerequisite_children: Dict[str, List[str]] = {key: [] for key in TOPICS}
    prerequisite_indegree: Dict[str, int] = {key: 0 for key in TOPICS}
    for source, target in prerequisite_edges:
        prerequisite_children[source].append(target)
        prerequisite_indegree[target] += 1
    queue = [key for key, degree in prerequisite_indegree.items() if degree == 0]
    visited = 0
    while queue:
        source = queue.pop()
        visited += 1
        for target in prerequisite_children[source]:
            prerequisite_indegree[target] -= 1
            if prerequisite_indegree[target] == 0:
                queue.append(target)
    prerequisite_cycle_count = 0 if visited == len(TOPICS) else 1
    if prerequisite_cycle_count:
        errors.append("semantic graph contains a cycle in 'нужно до' prerequisites")

    incoming_counts = {
        key: sum(1 for _, _, target in declared_edges if target == key)
        for key in TOPICS
    }
    semantic_source_topics = sum(1 for count in incoming_counts.values() if count == 0)
    portugal_degree = sum(
        1 for source, _, target in declared_edges if source == "portugal" or target == "portugal"
    )
    area_contours = {
        tag.split("/", 2)[1]
        for tag in TOPIC_DOMAIN_TAG.values()
        if tag.startswith("область/") and len(tag.split("/", 2)) == 3
    }
    if not 8 <= len(area_contours) <= 10:
        errors.append(f"expected 8–10 stable top-level area contours, got {sorted(area_contours)}")

    for route_key in ("long", "group_route", "technology"):
        missing_education = [
            key for key in ("early_education", "school_education", "higher_education")
            if key not in ROUTES[route_key].topics
        ]
        if missing_education:
            errors.append(f"route {route_key} does not expose all education stages: {missing_education}")

    for route in ROUTES.values():
        expected = generated_target(route.filename)
        if expected not in WIKILINK_RE.findall(index):
            errors.append(f"route is not one click from index: {route.filename}")
        related_count = section_link_count(rendered[route.filename], "Связанные человеческие страницы")
        if not 3 <= related_count <= 7:
            errors.append(f"route topic block must contain 3–7 links: {route.filename} has {related_count}")

    for filename, content in rendered.items():
        if f"[[{HOME_TARGET}|" in content:
            navigation_home_links += 1
        if "<details>" not in content or "</details>" not in content:
            errors.append(f"missing collapsed technical details: {filename}")
        first_screen = content.split("<details>", 1)[0]
        matches = RAW_BACKEND_RE.findall(first_screen)
        if matches:
            raw_first_screen += len(matches)
            errors.append(f"raw backend codes before technical details in {filename}: {sorted(set(matches))}")
        links = WIKILINK_RE.findall(content)
        wiki_count += len(links)
        for target in links:
            if not resolve_wikilink(target, desired_names):
                errors.append(f"broken wikilink: {filename} -> {target}")
        for heading in (
            "Откройте, если",
            "Что реально есть",
            "Сначала нужно",
            "Один следующий безопасный шаг",
            "Что станет возможно после",
        ):
            if f"## {heading}" not in content:
                errors.append(f"missing required section {heading!r}: {filename}")

    for topic in TOPICS.values():
        expected = generated_target(topic.filename)
        parent_routes = [
            route for route in ROUTES.values()
            if expected in WIKILINK_RE.findall(rendered[route.filename])
        ]
        if not parent_routes:
            errors.append(f"topic is not reachable within two clicks: {topic.filename}")

        content = rendered[topic.filename]
        expected_topic_id = f"картотека-тема-{Path(topic.filename).name.split(' — ', 1)[0]}"
        if f"id: {yaml_value(expected_topic_id)}" not in content:
            errors.append(f"topic frontmatter id mismatch: {topic.filename}")
        links = WIKILINK_RE.findall(content)
        expected_links = [generated_target(TOPICS[target].filename) for _, target in SEMANTIC_RELATIONS[topic.key]]
        if links != expected_links:
            errors.append(f"topic links do not exactly match declared semantic relations: {topic.filename}")
        allowed_prefix = f"{OUT.name}/{TOPICS_DIR_NAME}/"
        forbidden_fragments = (
            "00_HOME", HOME_TARGET, f"{OUT.name}/{Path(INDEX_NAME).stem}", f"{OUT.name}/{ROUTES_DIR_NAME}/",
            "/10 — Руководства/", "/20 — Рабочие разделы/", "/80_DATA_REGISTERS/",
            "/90_", "/MOCs/", "/Templates/", "/Notes/",
        )
        for target in links:
            if not target.startswith(allowed_prefix) or any(fragment in target for fragment in forbidden_fragments):
                topic_navigation_links += 1
                errors.append(f"topic contains forbidden navigation/technical link: {topic.filename} -> {target}")

        semantic = section_text(content, "Смысловые связи")
        relation_lines = re.findall(
            r"^- \*\*(Нужно до|Следующий шаг|Открывает|При аварии):\*\* \[\[([^\]|#]+)(?:\|[^\]]+)?\]\]$",
            semantic,
            flags=re.MULTILINE,
        )
        if len(relation_lines) != len(links) or not 2 <= len(relation_lines) <= 4:
            errors.append(f"semantic relation block invalid: {topic.filename}")
        semantic_topic_links += len(relation_lines)
        if f"[[{HOME_TARGET}" in content or "[[00_HOME" in content or generated_target(INDEX_NAME) in content or f"/{ROUTES_DIR_NAME}/" in content:
            errors.append(f"topic contains universal navigation backlink: {topic.filename}")

        planned_rows = future_card_rows(topic)
        backlog = section_text(content, "Будущие конкретные карточки")
        missing_names = [name for name, _, _, _ in planned_rows if name not in backlog]
        if missing_names:
            errors.append(f"future-card rows missing in {topic.filename}: {missing_names[:3]}")
        table_rows = [line for line in backlog.splitlines() if line.startswith("| ")]
        # One header plus one line for every planned card; the delimiter starts
        # with '|---' and is intentionally not included here.
        if len(table_rows) != len(planned_rows) + 1:
            errors.append(f"future-card table row mismatch in {topic.filename}: {len(table_rows) - 1} != {len(planned_rows)}")

        tags = topic_tags(topic.key)
        domain_tags = [tag for tag in tags if tag.startswith("область/")]
        if len(tags) not in (5, 6, 7):
            errors.append(f"topic tag count must be 5–7: {topic.filename} has {len(tags)}")
        if len(set(tags)) != len(tags):
            errors.append(f"topic has duplicate controlled tags: {topic.filename}")
        if len(domain_tags) != 1:
            errors.append(f"topic must have exactly one domain tag: {topic.filename}")
        unknown_tags = sorted(set(tags) - set(ALLOWED_TOPIC_TAGS))
        if unknown_tags:
            errors.append(f"topic has uncontrolled tags: {topic.filename}: {unknown_tags}")
        english_tags = [tag for tag in tags if re.search(r"[A-Za-z]", tag)]
        if english_tags:
            errors.append(f"topic has English-visible tag values: {topic.filename}: {english_tags}")
        if f"тип: {yaml_value('тип/тема')}" not in content:
            errors.append(f"topic lacks controlled Russian type field: {topic.filename}")
        for tag in tags:
            if f"  - {yaml_value(tag)}" not in content:
                errors.append(f"topic frontmatter lacks expected controlled tag: {topic.filename}: {tag}")
        expected_age = EDUCATION_AGE_TAG.get(topic.key)
        actual_age = [tag for tag in tags if tag.startswith("возраст/")]
        if expected_age and actual_age != [expected_age]:
            errors.append(f"education topic age tag mismatch: {topic.filename}")
        if not expected_age and actual_age:
            errors.append(f"non-education topic has an age tag: {topic.filename}")

    plant_text = rendered[TOPICS["wild_plants"].filename]
    mushroom_text = rendered[TOPICS["mushrooms"].filename]
    for filename, text in ((TOPICS["wild_plants"].filename, plant_text), (TOPICS["mushrooms"].filename, mushroom_text)):
        required = ("фотограф", "ИИ", "видовая карточка", "опасные двойники", "сезон", "место", "право", "эксперт", "видоспецифичная обработка", "НЕ УПОТРЕБЛЯТЬ")
        missing = [value for value in required if value not in text]
        if missing:
            errors.append(f"foraging safety boundary incomplete in {filename}: {missing}")

    if "```mermaid" not in index or "## Обычное дерево ссылок" not in index:
        errors.append("index must contain Mermaid map and ordinary link tree")
    if topic_navigation_links:
        errors.append(f"topic navigation-link invariant failed: {topic_navigation_links} forbidden links")
    if "изготовления современного оружия" not in rendered[TOPICS["hunting"].filename]:
        errors.append("hunting/protection page lacks explicit modern-weapon fabrication boundary")
    for token in ("Камень как ударный инструмент", "Рукоять ручного инструмента", "Кузнечные клещи", "Лопата", "Угол заточки", "Испытание нагрузки"):
        if token not in rendered[TOPICS["tools"].filename]:
            errors.append(f"tool evolution backlog missing {token!r}")
    for token in ("пресноводное", "эстуария", "морское", "Узел", "Разделка", "Холодовая цепь", "Ремонт"):
        if token not in rendered[TOPICS["fishing"].filename]:
            errors.append(f"fishing backlog missing {token!r}")
    for token in ("семьи", "жиль", "вода", "пищ", "медицин", "живот", "растен", "инструмент"):
        if token.casefold() not in rendered[TOPICS["winter"].filename].casefold():
            errors.append(f"winter backlog missing scope token {token!r}")
    if errors:
        die("generated knowledge route verification failed:\n- " + "\n- ".join(errors[:80]))
    return {
        "pages": len(rendered),
        "routes": len(ROUTES),
        "topics": len(TOPICS),
        "future_cards": future_cards,
        "unique_future_cards": unique_future_cards,
        "wikilinks": wiki_count,
        "semantic_topic_links": semantic_topic_links,
        "semantic_unique_edges": len(directed_pairs),
        "semantic_reciprocal_pairs": len(reciprocal_pairs),
        "semantic_prerequisite_cycles": prerequisite_cycle_count,
        "semantic_source_topics": semantic_source_topics,
        "portugal_semantic_degree": portugal_degree,
        "topic_area_contours": len(area_contours),
        "topic_tags_min": min(len(topic_tags(key)) for key in TOPICS),
        "topic_tags_max": max(len(topic_tags(key)) for key in TOPICS),
        "topic_navigation_links": topic_navigation_links,
        "topic_home_backlinks": 0,
        "navigation_home_links": navigation_home_links,
        "broken_links": 0,
        "raw_codes_first_screen": raw_first_screen,
    }


def is_owned_page(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        prefix = path.read_text(encoding="utf-8")[:1200]
    except (OSError, UnicodeDecodeError):
        return False
    return (
        prefix.startswith("---\n")
        and "generated: true" in prefix
        and f"generator: {yaml_value(GENERATOR_ID)}" in prefix
        and INSTRUCTION_STATE in prefix
    )


def safe_owned_target(relative_name: str) -> Path:
    relative = Path(relative_name)
    if (
        relative.is_absolute()
        or "\\" in relative_name
        or relative.suffix != ".md"
        or any(part in ("", ".", "..") or part.startswith(".") for part in relative.parts)
    ):
        die(f"unsafe owned relative path: {relative_name!r}")
    target = OUT / relative
    resolved_out = OUT.resolve()
    resolved_parent = target.parent.resolve()
    if resolved_parent != resolved_out and resolved_out not in resolved_parent.parents:
        die(f"owned path escapes through a symlink: {relative_name!r}")
    if target.is_symlink():
        die(f"refusing to use symlink as owned page: {target}")
    return target


def load_manifest() -> Tuple[Set[str], Dict[str, str]]:
    if not MANIFEST.exists():
        return set(), {}
    try:
        data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        die(f"cannot read owned manifest: {exc}")
    if data.get("generator") != GENERATOR_ID or not isinstance(data.get("generated_files"), list):
        die("manifest is not owned by this generator")
    result: Set[str] = set()
    for raw in data["generated_files"]:
        if not isinstance(raw, str):
            die("manifest contains a non-string generated filename")
        path = Path(raw)
        if (
            path.is_absolute()
            or "\\" in raw
            or path.suffix != ".md"
            or any(part in ("", ".", "..") or part.startswith(".") for part in path.parts)
        ):
            die(f"unsafe path in manifest: {raw!r}")
        result.add(raw)
    raw_hashes = data.get("generated_sha256", {})
    if raw_hashes is None:
        raw_hashes = {}
    if not isinstance(raw_hashes, dict):
        die("manifest generated_sha256 is not an object")
    hashes: Dict[str, str] = {}
    for name, digest in raw_hashes.items():
        if name not in result or not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            die(f"manifest contains invalid generated hash: {name!r}")
        hashes[name] = digest
    if int(data.get("version", 1)) >= 2 and set(hashes) != result:
        die("version 2 manifest must hash every generated page")
    return result, hashes


def write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    with tempfile.NamedTemporaryFile(dir=str(path.parent), prefix=".knowledge-routes-tmp-", delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.chmod(temporary, 0o644)
        os.replace(str(temporary), str(path))
        os.chmod(path, 0o644)
    finally:
        if temporary.exists():
            temporary.unlink()


def release_version(technology: Sequence[Mapping[str, str]], gaps: Sequence[Mapping[str, str]]) -> str:
    versions = {row.get("release_version", "") for row in list(technology) + list(gaps)} - {""}
    if len(versions) != 1:
        die(f"expected one catalog release version, found {sorted(versions)}")
    return next(iter(versions))


