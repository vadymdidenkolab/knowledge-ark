def write_rendered(rendered: Mapping[str, str], metadata: Mapping[str, object]) -> Dict[str, int]:
    if OUT.is_symlink():
        die(f"refusing symlinked owned directory: {OUT}")
    OUT.mkdir(parents=True, exist_ok=True)
    old_owned, old_hashes = load_manifest()
    desired = set(rendered)
    deleted = 0
    for stale_name in sorted(old_owned - desired):
        stale = safe_owned_target(stale_name)
        if stale.exists():
            if not is_owned_page(stale):
                die(f"refusing to delete changed or user-owned stale file: {stale}")
            if stale_name in old_hashes and sha256_file(stale) != old_hashes[stale_name]:
                die(f"refusing to delete manually changed generated page: {stale}")
            stale.unlink()
            deleted += 1

    created = 0
    updated = 0
    unchanged = 0
    for name in sorted(desired):
        target = safe_owned_target(name)
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and name not in old_owned:
            die(f"refusing to overwrite unmanifested file: {target}")
        if target.exists() and not is_owned_page(target):
            die(f"refusing to overwrite changed or user-owned file: {target}")
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == rendered[name]:
            os.chmod(target, 0o644)
            unchanged += 1
            continue
        if target.exists() and name in old_hashes and sha256_file(target) != old_hashes[name]:
            die(f"refusing to overwrite manually changed generated page: {target}")
        write_atomic(target, rendered[name])
        if current is None:
            created += 1
        else:
            updated += 1

    manifest_data = {
        "version": 2,
        "generator": GENERATOR_ID,
        "owned_directory": OUT.name,
        "generated_files": sorted(desired),
        "generated_sha256": {name: sha256_text(rendered[name]) for name in sorted(desired)},
        **metadata,
    }
    manifest_text = json.dumps(manifest_data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != manifest_text:
        write_atomic(MANIFEST, manifest_text)
    else:
        os.chmod(MANIFEST, 0o644)
    return {"created": created, "updated": updated, "unchanged": unchanged, "deleted": deleted}


def main() -> int:
    try:
        rendered, metadata = build_rendered()
        write_counts = write_rendered(rendered, metadata)
    except (BuildError, OSError, csv.Error, ValueError) as exc:
        print(f"knowledge_routes_build_error {exc}", file=os.sys.stderr)
        return 1
    report = metadata["report"]
    if not isinstance(report, dict):
        print("knowledge_routes_build_error invalid internal report", file=os.sys.stderr)
        return 1
    counts = {**report, **write_counts}
