def _topic(
    key: str,
    number: int,
    title: str,
    open_if: str,
    existing: str,
    prerequisites: Sequence[str],
    next_step: str,
    unlocks: str,
    related: Sequence[str],
    dashboards: Sequence[str],
    guides: Sequence[str],
    domains: Sequence[str],
    catalog_terms: Sequence[str] = (),
    special_warning: str = "",
) -> Topic:
    return Topic(
        key=key,
        filename=f"{TOPICS_DIR_NAME}/{number:02d} — {title}.md",
        title=title,
        open_if=open_if,
        existing=existing,
        prerequisites=tuple(prerequisites),
        next_step=next_step,
        unlocks=unlocks,
        related=tuple(related),
        dashboards=tuple(dashboards),
        guides=tuple(guides),
        domains=tuple(domains),
        catalog_terms=tuple(catalog_terms),
        special_warning=special_warning,
    )


